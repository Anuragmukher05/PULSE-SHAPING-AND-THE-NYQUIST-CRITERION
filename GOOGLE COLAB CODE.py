# 6. GENERATE RC AND RRC PULSES
# ================================================================

RC = []
RRC = []

for alpha in alphas:

    RC.append(
        raised_cosine(t, Ts, alpha)
    )

    RRC.append(
        root_raised_cosine(t, Ts, alpha)
    )

RC = np.array(RC)
RRC = np.array(RRC)


