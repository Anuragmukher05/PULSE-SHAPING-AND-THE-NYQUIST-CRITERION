# ================================================================
# 19. BANDWIDTH VS ROLL-OFF FACTOR
# ================================================================

alpha_sweep = np.arange(
    0,
    1.001,
    0.05
)

# Theoretical bandwidth
B_theory = (
    1 + alpha_sweep
) / (2 * Ts)

B_measured = np.zeros(
    len(alpha_sweep)
)


# ================================================================
# 20. MEASURE BANDWIDTH USING FFT
# ================================================================

for i, alpha in enumerate(alpha_sweep):

    hh = raised_cosine(
        t,
        Ts,
        alpha
    )

    H = np.abs(
        np.fft.fftshift(
            np.fft.fft(hh, Nfft)
        )
    )

    H = H / np.max(H)

    positive = f >= 0

    f_positive = f[positive]
    H_positive = H[positive]

    # Find first frequency below 1%
    indices = np.where(
        H_positive < 0.01
    )[0]

    if len(indices) > 0:

        index = indices[0]

    else:

        index = len(f_positive) - 1

    B_measured[i] = f_positive[index]


# ================================================================
# 21. PLOT BANDWIDTH VS ROLL-OFF
# ================================================================

plt.figure(figsize=(10, 6))

plt.plot(
    alpha_sweep,
    B_theory,
    linewidth=1.8,
    label='Theory: (1+α)/(2Ts)'
)

plt.plot(
    alpha_sweep,
    B_measured,
    'o',
    label='Measured using FFT'
)

