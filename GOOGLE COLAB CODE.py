# ================================================================

# np.sinc(x) = sin(pi*x)/(pi*x)
sinc_pulse = np.sinc(t / Ts)


# ================================================================
# 4. RAISED COSINE FUNCTION
# ================================================================

def raised_cosine(t, Ts, alpha):

    t = np.asarray(t, dtype=float)

    h = np.zeros_like(t)

    if alpha == 0:

        h = np.sinc(t / Ts)

    else:

        # Normal RC equation
        denominator = 1 - (2 * alpha * t / Ts)**2

        # Normal case
        normal = np.abs(denominator) > 1e-10

        x = np.pi * t / Ts

        h[normal] = (
            np.sin(x[normal]) / x[normal]
            * np.cos(np.pi * alpha * t[normal] / Ts)
            / denominator[normal]
        )

        # t = 0
        zero = np.abs(t) < 1e-10
        h[zero] = 1.0

        # t = +/- Ts/(2*alpha)
        singular = (
            np.abs(np.abs(2 * alpha * t / Ts) - 1)
            < 1e-10
        )

        h[singular] = (
            alpha / 2
            * np.sin(np.pi / (2 * alpha))
        )

    return h


# ================================================================
# 5. ROOT RAISED COSINE FUNCTION
# ================================================================

def root_raised_cosine(t, Ts, alpha):

    t = np.asarray(t, dtype=float)

    h = np.zeros_like(t)

    if alpha == 0:

        h = np.sinc(t / Ts) / np.sqrt(Ts)

    else:

        # Normal RRC equation
        numerator = (
            np.sin(
                np.pi * t / Ts * (1 - alpha)
            )
            +
            4 * alpha * t / Ts
            *
            np.cos(
                np.pi * t / Ts * (1 + alpha)
            )
        )

        denominator = (
            np.pi * t / Ts
            *
            (1 - (4 * alpha * t / Ts)**2)
        )

        # Normal points
        normal = (
            (np.abs(t) > 1e-10)
            &
            (np.abs(np.abs(4 * alpha * t / Ts) - 1)
             > 1e-10)
        )

        h[normal] = (
            numerator[normal]
            /
            denominator[normal]
            /
            np.sqrt(Ts)
        )

        # t = 0
        zero = np.abs(t) < 1e-10

        h[zero] = (
            (1 / np.sqrt(Ts))
            *
            (1 - alpha + 4 * alpha / np.pi)
        )

        # t = +/- Ts/(4*alpha)
        singular = (
            (np.abs(t) > 1e-10)
            &
            (
                np.abs(
                    np.abs(4 * alpha * t / Ts) - 1
                ) < 1e-10
            )
        )

        a = alpha

        h[singular] = (
            a / np.sqrt(2 * Ts)
            *
            (
                (1 + 2/np.pi)
                * np.sin(np.pi/(4*a))
                +
                (1 - 2/np.pi)
                * np.cos(np.pi/(4*a))
            )
        )

    return h


